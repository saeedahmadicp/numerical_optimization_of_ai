def gauss_patterson(
    problem: Problem | Callable[[float], float], *, tol: float, max_level: int = MAX_LEVEL
) -> Result:
    """Non-adaptive nested Gauss–Kronrod–Patterson quadrature with the stopping test of CC.

    Step k applies the N_k = 2^{k+1} − 1 point rule on [a, b]; converged=True at the first k ≥ 2
    with |I_k − I_{k−1}| ≤ tol·max(1, |I_k|); converged=False after ``max_level`` or on a
    non-finite value. f is cached by abscissa, so a run stopping at level K costs N_K evaluations.
    """
    prob = scalar_problem(problem)
    if not (math.isfinite(tol) and tol > 0):
        raise ValueError(f"tol must be a positive finite number, got {tol!r}")
    if not 2 <= max_level <= MAX_LEVEL:
        raise ValueError(f"max_level must be in [2, {MAX_LEVEL}], got {max_level}")
    a, b = (float(v) for v in prob.domain)
    half, mid = 0.5 * (b - a), 0.5 * (a + b)
    exact = None if prob.exact is None else float(prob.exact)
    counted = Counted(prob.f)
    cache_: dict[float, float] = {}

    def f(x: float) -> float:
        if x not in cache_:
            try:
                with np.errstate(all="ignore"):
                    cache_[x] = float(counted(x))
            except (ArithmeticError, ValueError):  # as clenshaw_curtis: a failed f is NaN
                cache_[x] = math.nan
        return cache_[x]

    trace: list[Step] = []
    est, err_est = math.nan, None
    extra: dict[str, Any] = {}
    rules = patterson_rules()
    for k in range(max_level + 1):
        t, w = rules[k]
        x = mid + half * t  # (N_k,) the same doubles at every level, so the cache is exact
        n_before = counted.n
        vals = [f(float(xi)) for xi in x]
        prev, est = est, math.fsum((half * w * np.array(vals)).tolist())
        if k > 0:
            err_est = abs(est - prev)
        error = None if exact is None else abs(est - exact)
        trace.append(
            Step(
                k,
                est,
                est,
                info={
                    "estimate": est,
                    "error": error,
                    "err_est": err_est,
                    "n_points": int(t.size),
                    "new_nodes": counted.n - n_before,
                },
            )
        )
        extra = {"exact": exact, "error": error, "err_est": err_est, "n_points": int(t.size)}
        if not (math.isfinite(est) and all(math.isfinite(v) for v in vals)):
            return Result("gauss_patterson", est, est, False, "non-finite value", k, counted.n,
                          trace=trace, extra=extra)  # fmt: skip
        if k >= 2 and err_est is not None and err_est <= tol * max(1.0, abs(est)):
            return Result("gauss_patterson", est, est, True, f"passed with {t.size} points", k,
                          counted.n, trace=trace, extra=extra)  # fmt: skip
    return Result("gauss_patterson", est, est, False,
                  f"reached the largest rule ({rules[max_level][0].size} points)", max_level,
                  counted.n, trace=trace, extra=extra)  # fmt: skip


def quadpack_qags(
    problem: Problem | Callable[[float], float],
    *,
    tol: float,
    epsabs: float | None = None,
    limit: int = 200,
) -> Result:
    """``scipy.integrate.quad`` (QUADPACK QAGS: adaptive G10/K21 with ε-extrapolation).

    Requested accuracy |I − I_est| ≤ max(epsabs, tol·|I_est|). The default epsabs = tol makes this
    max(tol, tol·|I|) = tol·max(1, |I|), the acceptance scale that every method in E3 is judged on
    and the stopping scale of ``clenshaw_curtis``. converged = QUADPACK's ier == 0. The cost is the
    number of f calls (each subinterval costs 21; equal to QUADPACK's ``neval``).
    """
    from scipy.integrate import quad

    prob = scalar_problem(problem)
    a, b = (float(v) for v in prob.domain)
    counted = Counted(prob.f)
    eps_abs = tol if epsabs is None else epsabs
    with warnings.catch_warnings():
        warnings.simplefilter("ignore")
        out = quad(counted, a, b, epsabs=eps_abs, epsrel=tol, limit=limit, full_output=1)
    est, abserr, info = float(out[0]), float(out[1]), out[2]
    converged = len(out) == 3  # quad appends a message only when ier > 0
    exact = None if prob.exact is None else float(prob.exact)
    extra = {
        "exact": exact,
        "error": None if exact is None else abs(est - exact),
        "err_est": abserr,
        "neval": int(info["neval"]),
        "subintervals": int(info["last"]),
        "message": "" if converged else str(out[3]).splitlines()[0],
    }
    msg = "QUADPACK ier = 0" if converged else f"QUADPACK: {extra['message']}"
    # QUADPACK is a black box here: the trace holds one step, the final estimate.
    trace = [Step(0, est, est, info={"estimate": est, "error": extra["error"], "err_est": abserr})]
    return Result("quadpack_qags", est, est, converged, msg, int(info["last"]), counted.n,
                  trace=trace, extra=extra)  # fmt: skip


